#!/usr/bin/env node
// Spambank T7 (BUILD.md 12.2/12.3): embeds the counter-spam reply's content in a TypeScript module.
//
//   node scripts/gen-spambank-autoreply-content.mjs
//
// The worker and the API are esbuild bundles (scripts/build-service.mjs), so a .txt, .html or .png
// next to the source would not ship. The files in autoreply/content/ stay the source of truth (the
// owner's drafts, with {{ABN}}, {{CONTACT_EMAIL}} and {{OPTOUT_URL}} filled per reply); this writes
// them into content.generated.ts, and content.test.ts fails when the two disagree.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "apps/api/src/modules/spambank/autoreply");
const read = (name) => readFileSync(path.join(dir, "content", name));

const text = read("reply-en-AU.txt").toString("utf8");
const html = read("reply-en-AU.html").toString("utf8");
const png = read("banner.png");

const out = `// Generated by scripts/gen-spambank-autoreply-content.mjs from ./content. Do not edit by hand.
// Listed in .prettierignore and eslint.config.mjs's ignores.

/** \`content/reply-en-AU.txt\`: the first line is the subject. */
export const REPLY_TEXT_EN_AU = ${JSON.stringify(text)};

/** \`content/reply-en-AU.html\`: the text/html part; the banner is \`cid:god-banner\`. */
export const REPLY_HTML_EN_AU = ${JSON.stringify(html)};

/** \`content/banner.png\`, 1200x600, sent inline (never a remote image). */
export const BANNER_PNG_SHA256 = ${JSON.stringify(createHash("sha256").update(png).digest("hex"))};
export const BANNER_PNG_BASE64 = ${JSON.stringify(png.toString("base64"))};
`;
writeFileSync(path.join(dir, "content.generated.ts"), out);
console.log(`wrote content.generated.ts (${String(out.length)} bytes)`);
